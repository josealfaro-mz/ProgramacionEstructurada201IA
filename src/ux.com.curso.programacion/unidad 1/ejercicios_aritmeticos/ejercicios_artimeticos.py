# Ejemplo de uso de operadores aritméticos en Python
def ejercicios():
    # Suma
    suma = 5 + 3
    print(f"Suma: {suma}")

    # Resta
    resta = 10 - 4
    print(f"Resta: {resta}")

    # Multiplicación
    multiplicacion = 6 * 7
    print(f"Multiplicación: {multiplicacion}")

    # División Entera
    division_entera = 10 // 3
    print(f"División Entera: {division_entera}")

    # Módulo
    modulo = 10 % 3
    print(f"Módulo: {modulo}")

# Potenciación
    potenciacion = 2 ** 3
    print(f"Potenciación: {potenciacion}")

def main():
    ejercicios()

if __name__ == "__main__":
    main()